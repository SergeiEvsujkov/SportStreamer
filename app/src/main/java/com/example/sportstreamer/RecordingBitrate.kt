package com.example.sportstreamer

/**
 * Битрейт локальной записи в память.
 *
 * Действует только когда трансляция в интернет выключена. Если писать одновременно с эфиром,
 * энкодер один на двоих, поэтому файл получает битрейт потока — его подстраивает адаптация
 * под канал.
 *
 * Значения хранятся в настройках как число Мбит/с, чтобы варианты в меню и расчёты были в одном
 * месте и их можно было проверить тестами.
 */
object RecordingBitrate {

    /** По умолчанию пишем в 5 Мбит/с — как в исходной версии приложения. */
    const val DEFAULT_MBPS = 5

    /** Варианты в настройках: 1, 3, 5 Мбит/с. */
    val OPTIONS = listOf(1, 3, 5)

    /** Битрейт для энкодера в битах в секунду. Неизвестное значение заменяется на [DEFAULT_MBPS]. */
    fun bitsPerSecond(mbps: Int): Int = valid(mbps) * MEGABIT

    /** Оценка размера файла: МБ в минуту. Полезно в подсказке на экране настроек. */
    fun megabytesPerMinute(mbps: Int): Int = valid(mbps) * 60 / 8

    private fun valid(mbps: Int): Int = if (mbps in OPTIONS) mbps else DEFAULT_MBPS

    private const val MEGABIT = 1024 * 1024
}
